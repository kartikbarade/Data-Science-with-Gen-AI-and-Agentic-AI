# Literals in Python
"""A literal in Python is a fixed value that you directly write in your program.
 Python creates the corresponding data value from that written representation.
"""
# example
name = "Kartik Barade"  # String literal
age = 21  # Integer literal
CGPA = 8.5  # Float literal
is_student = True  # Boolean literal
x = 2 + 3j  # Complex literal

marks = [85, 90, 78, 92]  # List literal
numbers = (1, 2, 3, 4)  # Tuple literal
num_dict = {"name": "Kartik", "age": 21}  # Dictionary literal
num_set = {1, 2, 3, 4}  # Set literal
